// T046–T047 (003 FR-031, research R11): screenshot every screen from tag prototype-v0.1.0 ("before") and from the
// current prototype ("after"), then build docs/design/round1-before-after.md from docs/design/round1/notes.json.
import { execFileSync } from 'node:child_process';
import { existsSync, rmSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';
import { ROOT } from './lib.mjs';

const SCREENS = ['welcome', 'age-select', 'avatar', 'parent-gate', 'home', 'mission-intro', 'activity-find', 'activity-sort',
  'activity-count', 'decision', 'result-save', 'result-spend', 'summary', 'reward', 'wallet', 'progress'];
const OUT = path.join(ROOT, 'docs/design/round1');
const BEFORE = path.join(ROOT, 'tools/design/.tmp/before');
mkdirSync(path.join(OUT, 'before'), { recursive: true });
mkdirSync(path.join(OUT, 'after'), { recursive: true });

if (existsSync(BEFORE)) { execFileSync('git', ['worktree', 'remove', '--force', BEFORE], { cwd: ROOT }); }
execFileSync('git', ['worktree', 'add', '--detach', BEFORE, 'prototype-v0.1.0'], { cwd: ROOT, stdio: 'ignore' });

const browser = await chromium.launch();
async function shoot(protoRoot, dir) {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, reducedMotion: 'reduce' });
  await page.goto(pathToFileURL(path.join(protoRoot, 'prototype/index.html')).href + '#/welcome');
  await page.waitForTimeout(400);
  for (const s of SCREENS) {
    await page.evaluate((id) => {
      const KC = window.KC;
      KC.state.lostCoins.found = 8;
      KC.state.lostCoins.choice = id === 'result-spend' ? 'spend' : 'save';
      KC.go(id);
    }, s);
    await page.waitForTimeout(1000);
    await page.screenshot({ path: path.join(OUT, dir, `${s}.png`) });
  }
  await page.close();
}
try {
  await shoot(BEFORE, 'before');
  await shoot(ROOT, 'after');
} finally {
  await browser.close();
  execFileSync('git', ['worktree', 'remove', '--force', BEFORE], { cwd: ROOT });
}

// Build the client summary from notes.json.
const notes = JSON.parse(readFileSync(path.join(OUT, 'notes.json'), 'utf8'));
const icon = { brand: '🎨 Brand', voice: '🎙️ Voice', interaction: '👆 Interaction' };
let md = `# Round 1: What Changed, Screen by Screen

**For**: Jefferson Agbai (client).

**Prototype**: v0.1.0 → **v0.2.0**.

**Your round-1 feedback**:

1. Apply the official KudiCubs brand.
2. Replace the robot voice with a natural human voice.
3. Make it more interactive.

Each screen below shows **before** (left) and **after** (right), with what changed. The images
are generated by \`tools/design/capture-before-after.mjs\`.

> **About the voice**: the human recordings haven't been made yet. Until they are, each line
> shows its words with a **"Recording pending"** badge. The robot voice has been removed
> completely.

`;
for (const s of SCREENS) {
  const n = notes.screens[s];
  if (!n) continue;
  md += `## ${n.title}\n\n| Before (v0.1.0) | After (v0.2.0) |\n|---|---|\n| ![before](./round1/before/${s}.png) | ![after](./round1/after/${s}.png) |\n\n`;
  md += n.changes.map((c) => `- **${icon[c.category]}**: ${c.note}`).join('\n') + '\n\n';
}
md += `## Decisions we need from you\n\n${notes.openDecisions.map((d, i) => `${i + 1}. **${d.title}**: ${d.question}`).join('\n')}\n`;
writeFileSync(path.join(ROOT, 'docs/design/round1-before-after.md'), md);
console.log(`before/after: ${SCREENS.length} screens × 2 → docs/design/round1/, round1-before-after.md`);
