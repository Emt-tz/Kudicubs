// T016: docs/design/narration/lines.json → docs/design/narration-script.md + prototype/assets/data/audio-manifest.js.
// Scans prototype/assets/audio/<lang>/<id>.m4a to mark each line recorded/pending (spec 003 FR-017–FR-019, research R5).
// --check: every line ≤ 8 s at the brief's pace, ≤ its maxSeconds, and every spoken key in the prototype exists.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import { ROOT, readJson } from './lib.mjs';

const LINES = path.join(ROOT, 'docs/design/narration/lines.json');
const SCHEMA = path.join(ROOT, 'specs/003-brand-voice-interactive/contracts/narration-lines.schema.json');
const SCRIPT = path.join(ROOT, 'docs/design/narration-script.md');
const MANIFEST = path.join(ROOT, 'prototype/assets/data/audio-manifest.js');
const AUDIO = path.join(ROOT, 'prototype/assets/audio');
const check = process.argv.includes('--check');

const doc = readJson(LINES);
const ajv = new Ajv2020({ allErrors: true, strict: false });
if (!ajv.validate(readJson(SCHEMA), doc)) {
  console.error('lines.json does not match narration-lines.schema.json:');
  for (const e of ajv.errors) console.error(`  ${e.instancePath || '/'} ${e.message}`);
  process.exit(1);
}

const problems = [];
const ids = new Set();
const words = (t) => t.replace(/[^\p{L}\p{N}'\s-]/gu, ' ').split(/\s+/).filter(Boolean).length;
const estimate = (t) => +(words(t) * 60 / doc.wordsPerMinute).toFixed(1);
for (const l of doc.lines) {
  if (ids.has(l.id)) problems.push(`duplicate line id ${l.id}`);
  ids.add(l.id);
  if (/\{[a-z]+\}/i.test(l.text)) problems.push(`${l.id}: recorded lines cannot contain variables ("${l.text}")`);
  const est = estimate(l.text);
  if (est > l.maxSeconds) problems.push(`${l.id}: ~${est}s at ${doc.wordsPerMinute} wpm is longer than maxSeconds ${l.maxSeconds}`);
}

// Manifest: every id in every language; recorded if the file exists.
const lines = {};
let recorded = 0;
for (const lang of doc.languages) {
  lines[lang] = {};
  const dir = path.join(AUDIO, lang);
  const present = new Set(existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.m4a')) : []);
  for (const l of doc.lines) {
    const has = present.has(`${l.id}.m4a`);
    if (has) recorded++;
    lines[lang][l.id] = { file: `assets/audio/${lang}/${l.id}.m4a`, status: has ? 'recorded' : 'pending' };
  }
  for (const f of present) if (!ids.has(f.replace(/\.m4a$/, ''))) problems.push(`audio/${lang}/${f}: no line with that id in lines.json`);
}
const text = Object.fromEntries(doc.lines.map((l) => [l.id, l.text]));
const manifest = {
  version: doc.version, defaultLanguage: doc.defaultLanguage, regionLanguage: doc.regionLanguage,
  languages: doc.languages, text, lines,
};
writeFileSync(MANIFEST, `/* GENERATED by tools/design/build-narration.mjs from docs/design/narration/lines.json — do not edit.
   Human recordings only: drop <lineId>.m4a into assets/audio/<lang>/ and re-run the script (spec 003 FR-019). */
window.KC = window.KC || {};
KC.audioManifest = ${JSON.stringify(manifest, null, 1)};
`);

// Actor's script, grouped by screen.
const byScreen = {};
for (const l of doc.lines) (byScreen[l.screen] = byScreen[l.screen] || []).push(l);
const order = ['welcome', 'age-select', 'avatar', 'parent-gate', 'home', 'mission-intro', 'activity-find', 'activity-sort', 'activity-count',
  'decision', 'result-save', 'result-spend', 'summary', 'reward', 'wallet', 'progress', 'any'];
const screens = Object.keys(byScreen).sort((a, b) => (order.indexOf(a) + 99 * (order.indexOf(a) < 0)) - (order.indexOf(b) + 99 * (order.indexOf(b) < 0)));
const esc = (s) => String(s || '').replace(/\|/g, '\\|');
let md = `# KudiCubs Narration Script

**For the voice actor.** Read [voice-direction-brief.md](./voice-direction-brief.md) first.
Generated by \`tools/design/build-narration.mjs\` from \`docs/design/narration/lines.json\` (v${doc.version}) — edit the JSON, not this file.

- **First recording language**: \`${doc.defaultLanguage}\` (Ghanaian English — **provisional**, pending client confirmation).
- **Pace**: about ${doc.wordsPerMinute} words per minute. **Every line ≤ 8 seconds, one idea per line.**
- **${doc.lines.length} lines.** Recorded so far: ${Object.values(lines[doc.defaultLanguage]).filter((x) => x.status === 'recorded').length} of ${doc.lines.length} in ${doc.defaultLanguage}.
- **File name** = the line ID + \`.wav\` (masters) or \`.m4a\` (prototype), e.g. \`intro.say.wav\`.

`;
for (const s of screens) {
  md += `## ${s === 'any' ? 'Shared (navigation, numbers, hints)' : 'Screen: `' + s + '`'}\n\n| ID | Line | Delivery | ≤ s (est.) | Idea | Say it like |\n|---|---|---|---|---|---|\n`;
  for (const l of byScreen[s]) {
    md += `| \`${l.id}\`${l.region ? ` (${l.region.toUpperCase()})` : ''} | ${esc(l.text)} | ${l.delivery} | ${l.maxSeconds} (${estimate(l.text)}) | ${esc(l.idea)} | ${esc(l.pronunciation)}${l.notes ? ' — ' + esc(l.notes) : ''} |\n`;
  }
  md += '\n';
}
md += `## File naming table\n\n| ID | Master file | Prototype file |\n|---|---|---|\n${doc.lines.map((l) => `| \`${l.id}\` | \`${l.id}.wav\` | \`prototype/assets/audio/<lang>/${l.id}.m4a\` |`).join('\n')}\n`;
writeFileSync(SCRIPT, md);

if (check) {
  // Every key the prototype speaks must exist.
  const src = ['app.js', 'screens.js', 'activities.js'].map((f) => readFileSync(path.join(ROOT, 'prototype/assets', f), 'utf8')).join('\n');
  const used = new Set();
  for (const m of src.matchAll(/KC\.voice\.play\('([a-z0-9_.]+)'/g)) used.add(m[1]);
  for (const m of src.matchAll(/(?:say|line|narration|hear):\s*'([a-z][a-z0-9_]*\.[a-z0-9_.]+)'/g)) used.add(m[1]);
  for (const m of src.matchAll(/'data-say':\s*'([a-z0-9_.]+)'/g)) used.add(m[1]);
  for (const k of used) {
    if (k.endsWith('.')) { if (![...ids].some((id) => id.startsWith(k))) problems.push(`prototype speaks '${k}…' but no line starts with it`); continue; } // dynamic prefix, e.g. 'num.' + n
    if (!ids.has(k)) problems.push(`prototype speaks '${k}' but it is not in lines.json`);
  }
  for (const l of doc.lines) if (l.maxSeconds > 8) problems.push(`${l.id}: maxSeconds over 8`);
}

if (problems.length) {
  console.error(problems.join('\n'));
  console.error(`\n${problems.length} narration problem(s).`);
  process.exit(1);
}
console.log(`narration v${doc.version}: ${doc.lines.length} lines × ${doc.languages.length} languages; ${recorded} recorded → narration-script.md + audio-manifest.js${check ? ' (check OK)' : ''}`);
