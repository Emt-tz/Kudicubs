// 004 T009: write prototype/assets/data/build-info.js (version, build date, commit) for the reviewer menu (FR-037).
//   node build-info.mjs [--date YYYY-MM-DD] [--commit abc1234]      (locally: builtAt 'local', commit null)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib.mjs';

const arg = (name) => { const i = process.argv.indexOf(name); return i > -1 ? process.argv[i + 1] : null; };
const mock = readFileSync(path.join(ROOT, 'prototype/assets/data/mock-data.js'), 'utf8');
const version = (mock.match(/prototype:\s*'([0-9.]+)'/) || [])[1];
if (!version) { console.error('KC.version.prototype not found in mock-data.js'); process.exit(1); }
const date = arg('--date');
if (date && !/^\d{4}-\d{2}-\d{2}$/.test(date)) { console.error('--date must be YYYY-MM-DD'); process.exit(1); }
const commit = arg('--commit');
if (commit && !/^[0-9a-f]{7,40}$/.test(commit)) { console.error('--commit must be a hex SHA'); process.exit(1); }
const build = { version, builtAt: date || 'local', commit: commit || null };
writeFileSync(path.join(ROOT, 'prototype/assets/data/build-info.js'),
  `/* GENERATED by tools/design/build-info.mjs — do not edit (004 FR-037). */\nwindow.KC = window.KC || {};\nKC.build = ${JSON.stringify(build)};\n`);
console.log(`build-info: v${build.version} · built ${build.builtAt}${build.commit ? ' · ' + build.commit : ''}`);
