// T007: every declared fg/bg pair in docs/design/tokens.json must meet WCAG AA (SC-003).
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT, TOKENS_JSON, readJson, tokenMap, resolve, contrast } from './lib.mjs';

const tokens = readJson(TOKENS_JSON);
const map = tokenMap(tokens);
let failed = 0;

console.log('fg                        bg                        ratio   min  result  usage');
for (const pair of tokens.pairs) {
  const fg = resolve(pair.fg, map);
  const bg = resolve(pair.bg, map);
  const ratio = contrast(fg, bg);
  const ok = ratio >= pair.minRatio;
  if (!ok) failed++;
  console.log(`${pair.fg.padEnd(26)}${pair.bg.padEnd(26)}${ratio.toFixed(2).padStart(5)}  ${String(pair.minRatio).padStart(4)}  ${ok ? 'PASS' : 'FAIL'}    ${pair.usage}`);
}

/* contrast-report.md (data-model §3): every used pair, then every rejected pair with its resolution. */
const used = tokens.pairs.map((p) => {
  const r = contrast(resolve(p.fg, map), resolve(p.bg, map));
  return `| \`${p.fg}\` | \`${p.bg}\` | ${p.usage} | ${p.minRatio === 3 ? 'large text / non-text' : 'text'} | ${r.toFixed(2)} | ${r >= p.minRatio ? '✅ pass' : '❌ fail'} |`;
});
const rejected = (tokens.rejectedPairs || []).map((p) => {
  const r = contrast(resolve(p.fg, map), resolve(p.bg, map));
  return `| \`${p.fg}\` | \`${p.bg}\` | ${p.usage} | ${r.toFixed(2)} | ${p.resolution} |`;
});
writeFileSync(path.join(ROOT, 'docs/design/contrast-report.md'), `# Contrast Report

Generated by \`tools/design/check-contrast.mjs\` from \`docs/design/tokens.json\` (tokens v${tokens.version}). WCAG 2.x:
4.5:1 for text, 3:1 for large text, icons and the outlines of controls. **No brand colour was altered** to pass:
failures are resolved with a different brand pairing or by not using the pairing (spec 003 FR-004).

## Pairings in use (${used.length})

| Foreground | Background | Used for | Requirement | Ratio | Result |
|---|---|---|---|---|---|
${used.join('\n')}

## Pairings that fail, and how they are avoided (${rejected.length})

| Foreground | Background | Where it would occur | Ratio | Resolution |
|---|---|---|---|---|
${rejected.join('\n')}
`);

if (failed) {
  console.error(`\n${failed} pair(s) below WCAG AA.`);
  process.exit(1);
}
console.log(`\nAll ${tokens.pairs.length} pairs meet WCAG AA.`);
