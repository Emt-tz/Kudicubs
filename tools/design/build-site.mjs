// 005 T012: build the shared pieces and assemble dist/ (the published set).
//   node build-site.mjs            sync shared/, generate sample-family.js, assemble dist/, write release.json
//   node build-site.mjs --check    verify everything generated is current and dist-ready (no writes)
// Sources: prototype/ (app, -> /app/), website/, dashboard/, hub/ (-> /), shared/ (-> /shared/).
import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync, cpSync, readdirSync } from 'node:fs';
import { execSync } from 'node:child_process';
import path from 'node:path';
import { ROOT, walk, readJson } from './lib.mjs';

const CHECK = process.argv.includes('--check');
const p = (...a) => path.join(ROOT, ...a);
const problems = [];
const fail = (m) => { problems.push(m); };

/* 1. shared/fonts and shared/brand are copies of the app's (one source of truth: prototype/assets). */
const SYNC = [
  ['prototype/assets/fonts', 'shared/fonts', null],
  ['prototype/assets/brand', 'shared/brand', /^(logo-on-white\.svg|logo-on-yellow\.svg|logo-on-brown\.svg|kudi-[a-z-]+\.webp|app-icon\.svg|app-icon-192\.png)$/]
];
for (const [from, to, only] of SYNC) {
  for (const f of readdirSync(p(from))) {
    if (only && !only.test(f)) continue;
    const a = p(from, f), b = p(to, f);
    if (CHECK) { if (!existsSync(b) || !readFileSync(a).equals(readFileSync(b))) fail(`${to}/${f} is out of date: run node tools/design/build-site.mjs`); }
    else { mkdirSync(p(to), { recursive: true }); cpSync(a, b); }
  }
}

/* 2. shared/sample-family.js from the JSON; Ama's events must equal the app's KC.sample (one family everywhere). */
const family = readJson(p('shared/sample-family.json'));
const js = `/* GENERATED by tools/design/build-site.mjs from shared/sample-family.json — do not edit (005 R6).\n   One fictional family for the website sign-in, Parent Dashboard and Team Console. */\nwindow.KC_FAMILY = ${JSON.stringify(family, null, 1)};\n`;
const target = p('shared/sample-family.js');
if (CHECK) { if (!existsSync(target) || readFileSync(target, 'utf8') !== js) fail('shared/sample-family.js is out of date'); }
else writeFileSync(target, js);
{
  const mock = readFileSync(p('prototype/assets/data/mock-data.js'), 'utf8');
  const block = mock.slice(mock.indexOf('KC.sample = {'));
  const appEvents = [...block.matchAll(/\{ t: '(\w+)', n: (\d+), ago: (\d+), label: '([\w.]+)'(?:, badge: '([\w.]+)')?(?:, pillar: '(\w+)')? \}/g)]
    .map((m) => ({ t: m[1], n: +m[2], ago: +m[3], label: m[4], ...(m[5] ? { badge: m[5] } : {}), ...(m[6] ? { pillar: m[6] } : {}) }));
  const ama = family.children.find((c) => c.nickname === 'Ama');
  if (JSON.stringify(appEvents) !== JSON.stringify(ama.events)) fail("Ama's events in shared/sample-family.json differ from KC.sample in prototype/assets/data/mock-data.js");
  const nick = new Set(family.children.map((c) => c.nickname));
  if (family.children.length < 3 || new Set(family.children.map((c) => c.ageBand)).size < 3 || new Set(family.children.map((c) => c.region)).size < 2)
    fail('sample family needs at least 3 children across 3 bands and 2 regions');
  if (nick.size !== family.children.length) fail('sample family nicknames must be unique');
}

/* 3. the published layout */
const OUT = p(process.env.KC_DIST || 'dist');     // KC_DIST lets parallel test runs use their own output folder
const SURFACES = [['prototype', 'app'], ['website', 'website'], ['dashboard', 'dashboard'], ['shared', 'shared']];
const pages = [];
function noindexOk(file) {
  const t = readFileSync(file, 'utf8');
  return /<meta[^>]+name=["']robots["'][^>]+noindex/i.test(t);
}
for (const [src, dest] of SURFACES) {
  if (!existsSync(p(src))) { if (src !== 'prototype' && src !== 'shared') continue; fail(`${src}/ is missing`); continue; }
  for (const f of walk(p(src))) {
    const rel = path.relative(p(src), f).split(path.sep).join('/');
    if (/node_modules|\.DS_Store|README\.md$/.test(rel)) continue;
    if (f.endsWith('.html')) { pages.push(path.join(dest, rel)); if (!noindexOk(f)) fail(`${src}/${rel}: missing <meta name="robots" content="noindex, nofollow">`); }
  }
}
if (existsSync(p("hub"))) { for (const f of readdirSync(p("hub"))) if (f.endsWith(".html")) { pages.push(f); if (!noindexOk(p("hub", f))) fail(`hub/${f}: missing noindex`); } }
else fail('hub/ is missing');

const git = (c, d) => { try { return execSync(c, { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { return d; } };
const mock = readFileSync(p('prototype/assets/data/mock-data.js'), 'utf8');
const version = (mock.match(/prototype:\s*'([0-9.]+)'/) || [])[1];
const coverage = (() => {
  const f = p('docs/design/journey-map.json');
  if (!existsSync(f)) return null;
  const rows = readJson(f).rows, c = { designed: 0, gap: 0, 'out-of-scope': 0 };
  rows.forEach((r) => { c[r.status] += 1; });
  return { designed: c.designed, gap: c.gap, outOfScope: c['out-of-scope'], total: rows.length };
})();
let changes = [];
if (existsSync(p('docs/design/release-notes.json'))) changes = readJson(p('docs/design/release-notes.json')).changes || [];
const release = { version, date: process.env.KC_BUILD_DATE || new Date().toISOString().slice(0, 10), commit: git('git rev-parse --short HEAD', null), coverage, changes };

if (CHECK) {
  if (problems.length) { console.error(problems.map((x) => '  ' + x).join('\n')); console.error(`build-site --check: ${problems.length} problem(s)`); process.exit(1); }
  console.log(`build-site --check: shared files current, ${pages.length} pages carry noindex`);
  process.exit(0);
}
if (problems.length) { console.error(problems.map((x) => '  ' + x).join('\n')); process.exit(1); }

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const [src, dest] of SURFACES) if (existsSync(p(src))) cpSync(p(src), path.join(OUT, dest), { recursive: true, filter: (s) => !/node_modules|README\.md$|\.DS_Store/.test(s) });
if (existsSync(p('hub'))) cpSync(p('hub'), OUT, { recursive: true });
/* hub-data.js: the release record and the journey rows, as a script so the hub also works without a network fetch */
const rowsForHub = existsSync(p('docs/design/journey-map.json')) ? readJson(p('docs/design/journey-map.json')).rows : [];
writeFileSync(path.join(OUT, 'hub-data.js'), `/* GENERATED by build-site.mjs: do not edit. */\nwindow.KC_HUB = ${JSON.stringify({ release, rows: rowsForHub })};\n`);
writeFileSync(path.join(OUT, 'robots.txt'), 'User-agent: *\nDisallow: /\n');
writeFileSync(path.join(OUT, 'release.json'), JSON.stringify(release, null, 2) + '\n');
/* The old root service worker (004 deployed the app at the site root) retires itself and clears its cache (research R3). */
writeFileSync(path.join(OUT, 'sw.js'), `/* Retires the pre-0.4.0 root service worker: the app now lives at /app/. */
self.addEventListener('install', function () { self.skipWaiting(); });
self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k.indexOf('kc-proto-') === 0 && k.indexOf('/app/') === -1; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.registration.unregister(); }));
});
`);
/* every local file a page references must exist in dist */
let missing = 0;
for (const page of pages) {
  const file = path.join(OUT, page);
  if (!existsSync(file)) continue;
  const html = readFileSync(file, 'utf8');
  for (const m of html.matchAll(/(?:src|href)=["']([^"'#?:]+)(?:[?#][^"']*)?["']/g)) {
    const ref = m[1];
    if (/^(https?:|mailto:|data:|\/\/)/.test(ref)) continue;
    const abs = path.normalize(path.join(path.dirname(file), ref));
    if (!abs.startsWith(OUT)) continue;
    if (!existsSync(abs) && !existsSync(path.join(abs, 'index.html'))) { console.error(`  ${page}: missing ${ref}`); missing += 1; }
  }
}
if (missing) { console.error(`build-site: ${missing} referenced file(s) missing from dist/`); process.exit(1); }
console.log(`build-site: dist/ ready (v${version}, ${pages.length} pages${coverage ? `, coverage ${coverage.designed}/${coverage.total} designed, ${coverage.gap} gap` : ''})`);
