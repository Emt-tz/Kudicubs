// T006: validate docs/design/tokens.json, then generate prototype/assets/tokens.css
// and the token tables inside docs/design/tokens.md. Deterministic output.
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import path from 'node:path';
import { ROOT, TOKENS_JSON, TOKENS_SCHEMA, TOKENS_CSS, TOKENS_MD, readJson, tokenMap, resolve, cssName } from './lib.mjs';

const tokens = readJson(TOKENS_JSON);
const schema = readJson(TOKENS_SCHEMA);
const ajv = new Ajv2020({ allErrors: true, strict: false });
if (!ajv.validate(schema, tokens)) {
  console.error('tokens.json does not match contracts/tokens.schema.json:');
  for (const e of ajv.errors) console.error(`  ${e.instancePath || '/'} ${e.message}`);
  process.exit(1);
}

const map = tokenMap(tokens);
const lines = [];
const rows = { color: [], typography: [], other: [] };

for (const [p, t] of map) {
  const v = resolve(t.$value, map);
  const alias = typeof t.$value === 'string' && t.$value.startsWith('{') ? t.$value : '';
  if (t.$type === 'typography') {
    const base = cssName(p);
    lines.push(`  ${base}-family: ${v.fontFamily};`);
    lines.push(`  ${base}-weight: ${v.fontWeight};`);
    lines.push(`  ${base}-size: ${v.fontSize};`);
    lines.push(`  ${base}-line: ${v.lineHeight};`);
    rows.typography.push(`| \`${p}\` | ${v.fontSize} / ${v.lineHeight} · ${v.fontWeight} · ${v.fontFamily.split(',')[0]} | ${t.$description} |`);
  } else if (t.$type === 'tint') {
    // A recorded colour at a recorded alpha (FR-002): the only way CSS may make a see-through colour.
    const base = t.$value.color.slice(1, -1);
    const css = `color-mix(in srgb, var(${cssName(base)}) ${t.$value.alpha}%, transparent)`;
    lines.push(`  ${cssName(p)}: ${css};`);
    rows.color.push(`| \`${p}\` | \`${t.$value.color}\` at ${t.$value.alpha}% | Tint of a recorded colour | ${t.$description} |`);
  } else {
    lines.push(`  ${cssName(p)}: ${v};`);
    const x = (t.$extensions && t.$extensions.kudicubs) || {};
    const prov = x.source === 'brand-guide' ? `Brand guide (${x.tier}${x.status !== 'confirmed' ? ', **' + x.status + '**' : ''})`
      : x.derivedFrom ? `Derived from \`${x.derivedFrom}\`: ${x.rule}`
      : x.notInPalette ? '**Not in brand palette**' : x.purpose ? 'Illustration palette' : alias ? 'Alias' : '';
    const flag = x.needsApproval ? ' ⚠ needs client approval' : '';
    const row = t.$type === 'color'
      ? `| \`${p}\` | \`${v}\`${alias ? ` (= \`${alias}\`)` : ''} | ${prov}${flag} | ${t.$description} |`
      : `| \`${p}\` | \`${v}\`${alias ? ` (= \`${alias}\`)` : ''} | ${t.$description} |`;
    (t.$type === 'color' ? rows.color : rows.other).push(row);
  }
}

const css = `/* GENERATED by tools/design/build-tokens.mjs from docs/design/tokens.json — do not edit.
   KudiCubs design tokens v${tokens.version} */

@font-face {
  font-family: 'Baloo 2';
  src: url('fonts/Baloo2-Variable.woff2') format('woff2');
  font-weight: 600 800;
  font-display: swap;
}
@font-face {
  font-family: 'Nunito';
  src: url('fonts/Nunito-Variable.woff2') format('woff2');
  font-weight: 400 800;
  font-display: swap;
}

:root {
  --kc-tokens-version: '${tokens.version}';
${lines.join('\n')}
}
`;
writeFileSync(TOKENS_CSS, css);
/* 005 T006: the same tokens for the website, dashboards and hub, plus the adult-surface density (research R7). */
const adult = `
/* Adult surfaces (website, dashboards, hub): same tokens, calmer and denser. */
[data-surface="adult"] {
  --kc-adult-type-scale: 0.9;
  --kc-adult-space-unit: var(--kc-space-3);
  --kc-adult-radius: var(--kc-radius-md);
  --kc-adult-target-min: 44px;
}
`;
writeFileSync(path.join(ROOT, 'shared/tokens.css'), css + adult);

const table = (head, r) => `| Token | Value | When to use |\n|---|---|---|\n${r.join('\n')}`;
const generated = `<!-- tokens:start -->
<!-- GENERATED by tools/design/build-tokens.mjs — edit docs/design/tokens.json, not this block. -->

**Token version**: \`${tokens.version}\`

### Colour

| Token | Value | Source | When to use |
|---|---|---|---|
${rows.color.join('\n')}

### Typography

${table('Typography', rows.typography)}

### Space, radius, elevation, size and motion

${table('Other', rows.other)}

### Checked contrast pairs

| Foreground | Background | Used for | Minimum |
|---|---|---|---|
${tokens.pairs.map((p) => `| \`${p.fg}\` | \`${p.bg}\` | ${p.usage} | ${p.minRatio}:1 |`).join('\n')}
<!-- tokens:end -->`;

let md = existsSync(TOKENS_MD) ? readFileSync(TOKENS_MD, 'utf8') : '# KudiCubs Design Tokens\n\n<!-- tokens:start -->\n<!-- tokens:end -->\n';
md = md.replace(/<!-- tokens:start -->[\s\S]*<!-- tokens:end -->/, generated);
writeFileSync(TOKENS_MD, md);

console.log(`tokens v${tokens.version}: ${map.size} tokens → prototype/assets/tokens.css, shared/tokens.css, docs/design/tokens.md`);
