// 005 T011/T018/T020: validate docs/design/journey-map.json and resolve every screen link in the platform manifests.
//   node check-coverage.mjs            progress mode: prints gaps, fails only on schema, missing stories or broken links
//   node check-coverage.mjs --strict   also fails on any in-scope gap
//   node check-coverage.mjs --write    regenerate docs/design/journey-map.md
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import path from 'node:path';
import { ROOT, readJson } from './lib.mjs';

const STRICT = process.argv.includes('--strict');
const WRITE = process.argv.includes('--write');
const mapArg = process.argv.indexOf('--map');   // used by the negative test with a doctored copy
const map = readJson(mapArg > -1 ? process.argv[mapArg + 1] : path.join(ROOT, 'docs/design/journey-map.json'));
const schema = readJson(path.join(ROOT, 'docs/design/schemas/journey-map.schema.json'));
const errors = [];

const ajv = new Ajv2020({ allErrors: true, strict: false });
if (!ajv.validate(schema, map)) for (const e of ajv.errors) errors.push(`journey-map.json ${e.instancePath || '/'} ${e.message}`);

/* manifests: one per surface; the dashboard file holds two keys */
const load = (f) => { const p = path.join(ROOT, f); return existsSync(p) ? readJson(p) : null; };
const manifests = {
  app: load('prototype/assets/data/screens.manifest.json'),
  website: load('website/screens.manifest.json'),
  hub: load('hub/screens.manifest.json')
};
const dash = load('dashboard/screens.manifest.json');
if (dash) { manifests['parent-dashboard'] = dash.parent || null; manifests['team-console'] = dash.team || null; }
const resolveScreen = (link) => {
  const m = manifests[link.platform];
  if (!m) return `no manifest for ${link.platform}`;
  const s = (m.screens || []).find((x) => x.id === link.screen);
  if (!s) return `screen "${link.screen}" is not in the ${link.platform} manifest`;
  for (const st of link.states || []) if (!(s.states || ['default']).includes(st)) return `state "${st}" is not listed for ${link.platform}/${link.screen}`;
  return null;
};

const ids = new Set();
for (const r of map.rows || []) {
  if (ids.has(r.id)) errors.push(`duplicate row id ${r.id}`); ids.add(r.id);
  if (r.status === 'designed') for (const l of r.screens || []) { const bad = resolveScreen(l); if (bad) errors.push(`${r.id} is "designed" but ${bad}`); }
}
for (const s of map.stories || []) if (!(map.rows || []).some((r) => r.source === s)) errors.push(`story ${s} has no row in the map`);
for (const r of map.rows || []) if (!(map.stories || []).includes(r.source)) errors.push(`${r.id} cites story ${r.source}, which is not in "stories"`);

const counts = {};
for (const r of map.rows || []) { const c = (counts[r.platform] ||= { designed: 0, gap: 0, 'out-of-scope': 0 }); c[r.status] += 1; }
const total = { designed: 0, gap: 0, 'out-of-scope': 0 };
for (const c of Object.values(counts)) for (const k of Object.keys(total)) total[k] += c[k];

console.log('coverage (designed / gap / out of scope):');
for (const [pl, c] of Object.entries(counts)) console.log(`  ${pl.padEnd(17)} ${c.designed} / ${c.gap} / ${c['out-of-scope']}`);
console.log(`  ${'TOTAL'.padEnd(17)} ${total.designed} / ${total.gap} / ${total['out-of-scope']}  (${(map.rows || []).length} rows, ${(map.stories || []).length} stories)`);
const gaps = (map.rows || []).filter((r) => r.status === 'gap');
if (gaps.length) {
  console.log(`${gaps.length} in-scope gap(s)${STRICT ? '' : ' (progress mode)'}:`);
  for (const r of gaps) console.log(`  ${r.id} [${r.platform}] ${r.title}`);
  if (STRICT) errors.push(`${gaps.length} in-scope row(s) have no designed screens`);
}

if (WRITE) {
  const L = ['# KudiCubs Journey and Story Map', '', '<!-- GENERATED by tools/design/check-coverage.mjs --write from journey-map.json: do not edit. -->', '',
    `Coverage: **${total.designed} designed**, **${total.gap} gaps**, ${total['out-of-scope']} out of scope (${(map.rows || []).length} rows).`, '',
    '| Platform | Designed | Gap | Out of scope |', '|---|---|---|---|', ...Object.entries(counts).map(([p, c]) => `| ${p} | ${c.designed} | ${c.gap} | ${c['out-of-scope']} |`), ''];
  for (const pl of Object.keys(counts)) {
    L.push(`## ${pl}`, '', '| Row | Story | Actor | Journey | Priority | Status | Screens |', '|---|---|---|---|---|---|---|');
    for (const r of map.rows.filter((x) => x.platform === pl))
      L.push(`| ${r.id} | ${r.source} | ${r.actor} | ${r.title} | ${r.priority} | ${r.status}${r.reason ? ' (' + r.reason + ')' : ''} | ${(r.screens || []).map((s) => '`' + s.screen + '`').join(', ')} |`);
    L.push('');
  }
  writeFileSync(path.join(ROOT, 'docs/design/journey-map.md'), L.join('\n'));
}
if (errors.length) { console.error('\n' + errors.map((e) => '  ✗ ' + e).join('\n')); console.error(`check-coverage: ${errors.length} problem(s)`); process.exit(1); }
console.log('check-coverage: ok' + (STRICT ? ' (strict)' : ''));
