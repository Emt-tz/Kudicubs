// T050 (003 FR-044; 004 T027 adds scratch MP3s and --check): generate prototype/sw.js — the offline cache list of every prototype file (brand assets,
// art, fonts, recordings) and a cache name derived from KC.version.prototype. Never edit sw.js by hand.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { ROOT, walk } from './lib.mjs';

const PROTO = path.join(ROOT, 'prototype');
const mock = readFileSync(path.join(PROTO, 'assets/data/mock-data.js'), 'utf8');
const version = (mock.match(/prototype:\s*'([0-9.]+)'/) || [])[1];
if (!version) { console.error('KC.version.prototype not found in mock-data.js'); process.exit(1); }
/* The cache name also carries the build stamp (004 review): every deploy gets a new sw.js, so returning devices
   install the new build instead of serving the old one from a cache named only by version. */
const info = readFileSync(path.join(PROTO, 'assets/data/build-info.js'), 'utf8');
const stamp = (info.match(/"commit":"([0-9a-f]+)"/) || info.match(/"builtAt":"([0-9a-z-]+)"/) || [, 'local'])[1];
const cacheName = `kc-proto-${version}-${stamp}`;

const files = walk(PROTO)
  .map((f) => path.relative(PROTO, f).split(path.sep).join('/'))
  .filter((f) => /\.(html|css|js|svg|png|webp|woff2|webmanifest|txt|m4a|mp3)$/.test(f) && f !== 'sw.js')
  .sort();

const out = `/* GENERATED by tools/design/build-sw.mjs — do not edit (003 FR-044).
   KudiCubs prototype offline cache (002 FR-023). Cache-first; registered only over http(s). */
var CACHE = '${cacheName}';
var FILES = [
  './',
${files.map((f) => `  '${f}',`).join('\n')}
];
self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) { return c.addAll(FILES); }).then(function () { return self.skipWaiting(); }));
});
self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k !== CACHE; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});
self.addEventListener('fetch', function (e) {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(function (hit) { return hit || fetch(e.request); }));
});
`;
const target = path.join(PROTO, 'sw.js');
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) {
    console.error('sw.js is out of date: run node tools/design/build-sw.mjs');
    process.exit(1);
  }
  console.log(`sw.js up to date: cache ${cacheName}, ${files.length} files`);
} else {
  writeFileSync(target, out);
  console.log(`sw.js: cache ${cacheName}, ${files.length} files`);
}
