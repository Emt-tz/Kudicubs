#!/usr/bin/env python3
"""Generate screen stubs, the registry and the app part of design/coverage-map.json.

Run from anywhere:  python3 app/tool/gen_screens.py [--force]

- lib/screens/<group>/<id>.dart  one stub per mobile canvas id. Existing files are
  NEVER overwritten (screen agents edit them) unless --force is given.
- lib/screens/registry.dart      always regenerated: `registry` (id -> builder) and `screenIndex`.
- design/coverage-map.json       only the top-level key "app" is rewritten.
"""
import json
import re
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
ROOT = APP.parent
FORCE = "--force" in sys.argv

GROUPS = {1: "onboarding", 2: "onboarding", 3: "auth", 4: "auth", 5: "auth", 6: "home", 7: "home",
          8: "missions_4_6", 9: "missions_4_6", 10: "missions_7_9", 11: "missions_10_15",
          12: "missions_10_15", 13: "wallet_profile", 14: "wallet_profile", 15: "parent",
          16: "parent", 17: "parent", 18: "system"}

# Flow routes in lib/core/router.dart (keep in sync): canvas id -> route.
FLOW_ROUTES = {
    "ob-01-splash": "/splash", "Main": "/welcome", "ob-02-intro-1": "/intro/1", "ob-03-intro-2": "/intro/2",
    "ob-04-intro-3": "/intro/3", "app-02-age": "/age", "app-03-avatar": "/avatar", "app-04-gate": "/gate",
    "au-01-pin-create": "/pin/create", "au-04-region": "/region", "au-05-email": "/email", "au-07-code": "/code",
    "au-12-joined": "/joined", "au-13-signin": "/signin", "app-05-home": "/home", "hm-06-daily-progress": "/daily",
    "app-06-mission-intro": "/mission/4-6", "ms-10-7-9-intro": "/mission/7-9", "ms-15-10-12-intro": "/mission/10-12",
    "ms-23-13-15-intro": "/mission/13-15", "app-14-wallet": "/wallet", "app-15-progress": "/progress",
    "pr-03-badge-earned": "/badges", "app-16-profile": "/profile", "app-17-parent-children": "/parent",
    "app-18-parent-child": "/parent/child/:id", "app-19-parent-settings": "/parent/settings",
    "sy-01-update-required": "/system/update-required", "sy-02-maintenance": "/system/maintenance",
    "sy-03-server-error": "/system/server-error", "sy-04-no-connection": "/system/no-connection",
    "sy-05-loading-generic": "/system/loading", "sy-06-empty-generic": "/system/empty",
}


def state_of(i, title):
    t = f"{i} {title}".lower()
    if "offline" in t or "no-connection" in t or "no connection" in t:
        return "offline"
    if "error" in t:
        return "error"
    if any(w in t for w in ("loading", "sending", "processing", "verifying")):
        return "loading"
    if "empty" in t:
        return "empty"
    return "normal"


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


index = [x for x in json.load(open(ROOT / "design/canvas-index.json")) if x["platform"] == "mobile"]
entries, imports, regs, metas = [], [], [], []
for x in index:
    i, title = x["id"], x["title"]
    n = int(re.match(r"App (\d+)", x["section"]).group(1))
    group, fn = GROUPS[n], "build_" + i.replace("-", "_")
    path = APP / "lib/screens" / group / f"{i}.dart"
    if FORCE or not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(f"""// ignore_for_file: non_constant_identifier_names
import 'package:flutter/material.dart';

import '../../core/screen_state.dart';
import '../../core/widgets/widgets.dart';

/// Canvas `{i}`: {title}. Section: {x["section"]}.
/// Replace the body with the real screen; keep the signature and the key.
Widget {fn}(BuildContext context, ScreenState state) {{
  return const ScreenScaffold(
    key: Key('screen-{i}'),
    title: {dart_str(title)},
    child: Center(child: Text('TODO {i}')),
  );
}}
""")
    imports.append(f"import '{group}/{i}.dart';")
    regs.append(f"  '{i}': {fn},")
    metas.append(f"  (id: '{i}', title: {dart_str(title)}, section: {dart_str(x['section'])}, group: '{group}'),")
    entries.append({"id": i, "platform": "app", "route": FLOW_ROUTES.get(i, f"/screen/{i}"), "state": state_of(i, title)})

(APP / "lib/screens/registry.dart").write_text(
    "// GENERATED by app/tool/gen_screens.py. Do not edit.\n"
    "import '../core/screen_state.dart';\n" + "\n".join(sorted(imports)) + "\n\n"
    "/// Canvas id -> screen builder (all 108 mobile screens).\n"
    "const Map<String, ScreenBuilder> registry = {\n" + "\n".join(regs) + "\n};\n\n"
    "/// Index for the /screens page, in design order.\n"
    "const List<({String id, String title, String section, String group})> screenIndex = [\n" + "\n".join(metas) + "\n];\n")

cov = ROOT / "design/coverage-map.json"
data = json.loads(cov.read_text()) if cov.exists() else {}
data["app"] = entries
cov.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
print(f"{len(entries)} screens, registry and coverage map written")
